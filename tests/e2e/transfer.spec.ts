import { expect, test } from '@playwright/test';
test.skip(!process.env.E2E_AUTH_TOKEN, 'Use the isolated authenticated browser harness.');
test('a team request with skills leads to a reviewed, dated permanent transfer', async ({page, context}) => {
  test.setTimeout(240_000);
  const cookie=(value:string)=>({name:'__Host-wi_session',value,domain:'localhost',path:'/',secure:true,httpOnly:true,sameSite:'Lax' as const});
  const signIn=async(value:string)=>context.addCookies([cookie(value)]);
  const owner=process.env.E2E_AUTH_TOKEN!, approvers=JSON.parse(process.env.E2E_TRANSFER_TOKENS!) as string[];
  await signIn(owner);
  await page.goto('/workspace/demand?date=2026-10-03');
  await page.getByRole('button',{name:/Add team request/}).click();
  const form=page.getByRole('dialog',{name:'Create Teams needing people'});
  await expect(form).toBeVisible();
  await form.getByRole('combobox',{name:'Organization',exact:true}).fill(process.env.E2E_TRANSFER_ORG_NAME!);
  await form.getByRole('option').filter({hasText:process.env.E2E_TRANSFER_ORG_NAME!}).click();
  await form.getByLabel(/Request code/).fill('E2E-RETENTION-NEED');
  await form.getByRole('combobox',{name:/Role/}).fill('Synthetic analyst');
  await form.getByRole('option').filter({hasText:'Synthetic analyst'}).click();
  await form.getByLabel(/Why people are needed/).fill('Retain an internal analyst for our team');
  await form.getByLabel(/Needed from/).fill('2026-11-01');
  await form.getByLabel(/Location/).fill('Chicago');
  await form.getByLabel(/Work mode/).selectOption('hybrid');
  await form.getByLabel(/Annual base salary budget/).fill('100000');
  await form.getByLabel(/Salary budget currency/).fill('USD');
  await form.getByRole('combobox',{name:'Required skill',exact:true}).fill('Synthetic SQL');
  await form.getByRole('option').filter({hasText:'Synthetic SQL'}).click();
  await form.getByRole('button',{name:'Add required skill'}).click();
  const create=page.waitForResponse(r=>r.url().endsWith('/api/team-needs')&&r.request().method()==='POST');
  await form.getByRole('button',{name:'Save record'}).click();
  const createResponse=await create; expect(createResponse.ok()).toBeTruthy(); const need=await createResponse.json();
  await expect(form).toBeHidden();
  const act=async(module:string,id:string,action:string,stage?:string)=>{
    const domain=module==='demand'?'demands':'movements';
    const load=page.waitForResponse(r=>r.url().includes(`/api/records/${domain}/${id}?`),{timeout:45_000});
    await page.goto(`/workspace/${module}?date=2026-11-01&id=${id}`);
    const loaded=await load; expect(loaded.ok(),await loaded.text()).toBeTruthy();
    const detail=page.getByRole('dialog'); await expect(detail).toBeVisible();
    if(stage) await detail.getByLabel('Approval stage').selectOption(stage);
    const response=page.waitForResponse(r=>r.url().endsWith('/api/actions')&&r.request().method()==='POST');
    await detail.getByRole('button',{name:action,exact:true}).click();
    const result=await response; expect(result.ok(),await result.text()).toBeTruthy(); return result.json();
  };
  await act('demand',need.id,'submit');
  for(const [index,stage] of ['manager','HR'].entries()) { await signIn(approvers[index]); await act('demand',need.id,'approve',stage); }
  await signIn(owner);
  await page.goto('/workspace/matches?date=2026-10-03');
  await page.getByRole('combobox',{name:/Team request/}).fill('E2E-RETENTION-NEED');
  await page.getByRole('option').filter({hasText:'E2E-RETENTION-NEED'}).click();
  await page.getByRole('button',{name:'Find matches',exact:true}).click();
  const candidate=page.getByRole('row').filter({hasText:'E2E-TRANSFER-PERSON'});
  await expect(candidate).toContainText('All required skills have current verified evidence');
  await expect(candidate).toContainText('Salary permission required');
  await candidate.getByRole('button',{name:/Propose transfer/}).click();
  const proposalForm=page.getByRole('form',{name:'Propose permanent transfer'});
  await proposalForm.getByRole('combobox',{name:/Destination manager/}).fill('E2E-DESTINATION-MANAGER');
  await proposalForm.getByRole('option').filter({hasText:'E2E-DESTINATION-MANAGER'}).click();
  await proposalForm.getByLabel('Transfer reason').fill('Both teams reviewed the placement and evidence');
  const save=page.waitForResponse(r=>r.url().endsWith('/api/transfers')&&r.request().method()==='POST');
  await proposalForm.getByRole('button',{name:'Save transfer proposal'}).click();
  const saved=await save; expect(saved.ok(),await saved.text()).toBeTruthy(); const proposal=await saved.json();
  await page.getByRole('link',{name:'Review and submit proposal'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await act('mobility',proposal.id,'submit');
  for(const [index,stage] of ['source-manager','destination-manager','HR','Finance'].entries()) { await signIn(approvers[index]); await act('mobility',proposal.id,'approve',stage); }
  await signIn(owner);
  const committed=await act('mobility',proposal.id,'commit');
  expect(committed.record.state).toBe('committed'); expect(JSON.stringify(committed)).not.toContain('91234'); expect(JSON.stringify(committed)).not.toContain('protected identity');
  const id=process.env.E2E_TRANSFER_WORKER_ID!;
  const before=await (await page.request.get(`/api/records/workers/${id}?date=2026-10-31`)).json();
  const after=await (await page.request.get(`/api/records/workers/${id}?date=2026-11-01`)).json();
  expect(before.orgId).toBe(process.env.E2E_ORG_ID); expect(after.orgId).toBe(process.env.E2E_TRANSFER_ORG_ID); expect(after.data.employmentStatus).toBe('active');
  const pool=await (await page.request.get('/api/records/redeployments?date=2026-11-01&considerForRoles=true')).json();
  expect(pool.rows.some((row:{workerId:string})=>row.workerId===id)).toBe(false);
  const assignments=await (await page.request.get('/api/records/assignments?date=2027-01-01')).json();
  const allocations=assignments.rows.filter((row:{workerId:string})=>row.workerId===id);
  expect(allocations).toHaveLength(1); expect(allocations[0].orgId).toBe(process.env.E2E_TRANSFER_ORG_ID); expect(allocations[0].validTo).toBeNull();
  await page.goto(`/workspace/mobility?date=2026-11-01&id=${proposal.id}`);
  await expect(page.getByRole('dialog')).toContainText('committed');
  await expect(page.getByRole('dialog')).toContainText('Finance ✓');
  await expect(page.getByRole('dialog').getByRole('button',{name:'commit',exact:true})).toHaveCount(0);
});
